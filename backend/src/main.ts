import { NestFactory } from '@nestjs/core';
import { ValidationPipe } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { NestExpressApplication } from '@nestjs/platform-express';
import { Logger } from 'nestjs-pino';
import { randomUUID } from 'node:crypto';
import cookieParser from 'cookie-parser';
import compression from 'compression';
import helmet from 'helmet';
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger';
import type { NextFunction, Request, Response } from 'express';
import { AppModule } from './app.module';
import { UPLOAD_DIR } from './uploads/uploads.controller';
import { GlobalExceptionFilter } from './common/filters/global-exception.filter';

/** Request id is attached by bootstrap for log correlation (M8). */
interface RequestWithId extends Request {
  id: string;
}

async function bootstrap() {
  const app = await NestFactory.create<NestExpressApplication>(AppModule, {
    // Buffer bootstrap logs until pino is wired up, then flush them into the
    // pino logger — nothing is lost or split across two loggers (Nest docs:
    // "custom logger" recipe).
    logger: false,
    bufferLogs: true,
  });
  const configService = app.get(ConfigService);
  app.useLogger(app.get(Logger));
  app.flushLogs();

  // Request ID for log correlation (M8).
  app.use((req: Request, _res: Response, next: NextFunction) => {
    const withId = req as RequestWithId;
    withId.id =
      (req.headers['x-request-id'] as string | undefined) ?? randomUUID();
    next();
  });

  app.use(cookieParser());

  // Uploaded images served from disk with 1-day browser cache (L1/L7).
  app.useStaticAssets(UPLOAD_DIR, { prefix: '/uploads', maxAge: '1d' });
  app.use(compression());
  app.use(
    helmet({
      contentSecurityPolicy: false,
      frameguard: { action: 'deny' },
      noSniff: true,
      referrerPolicy: { policy: 'strict-origin-when-cross-origin' },
    }),
  );

  const frontendUrl = configService.get<string>(
    'FRONTEND_URL',
    'http://localhost:3000',
  );
  app.enableCors({
    origin: [frontendUrl],
    credentials: true,
  });

  // OpenAPI docs at /docs (+ /docs-json for the raw spec). DTO schemas are
  // generated by the @nestjs/swagger CLI plugin configured in nest-cli.json.
  const swaggerConfig = new DocumentBuilder()
    .setTitle('Travel Board API')
    .setDescription(
      'NestJS API for the Travel Board app — auth, boards, social feeds, chat, places and uploads.',
    )
    .setVersion('1.0')
    .addBearerAuth(
      { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' },
      'bearer',
    )
    .build();
  const swaggerDocument = SwaggerModule.createDocument(app, swaggerConfig);
  SwaggerModule.setup('docs', app, swaggerDocument);

  app.useGlobalPipes(
    new ValidationPipe({
      whitelist: true,
      transform: true,
    }),
  );
  app.useGlobalFilters(new GlobalExceptionFilter());

  // Graceful shutdown: lets Nest deliver SIGTERM/SIGINT to modules (schedules,
  // sockets, DB pool) instead of exiting hard (Nest docs: lifecycle hooks).
  app.enableShutdownHooks();

  const port = Number(process.env.PORT ?? 4000);
  await app.listen(port);
  console.log(`Travel Board API listening on http://localhost:${port}`);
}

bootstrap().catch((error: unknown) => {
  // `void bootstrap()` hides DI/config failures behind a silent non-zero exit.
  // Print the root cause and fail loudly instead.
  console.error('Failed to start the API:');
  console.error(error);
  process.exit(1);
});
